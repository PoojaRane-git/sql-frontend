    private static boolean hasFindFilter(
            String query
    ) {

        String lower = query.toLowerCase();

        int findIndex =
                lower.indexOf(".find(");

        if (findIndex < 0) {
            return false;
        }

        int start =
                findIndex + ".find(".length();

        int end =
                query.indexOf(")", start);

        if (end < 0) {
            return false;
        }

        String inside =
                query.substring(start, end).trim();

        return !inside.isEmpty()
                && !inside.equals("{}");
    }


    private static boolean hasProjection(
            String query
    ) {

        String lower =
                query.toLowerCase();

        int findIndex =
                lower.indexOf(".find(");

        if (findIndex < 0) {
            return false;
        }

        int start =
                findIndex + ".find(".length();

        int end =
                query.indexOf(")", start);

        if (end < 0) {
            return false;
        }

        String inside =
                query.substring(start, end);

        /*
         * A second object after the first find() argument
         * represents projection.
         */
        int comma =
                inside.indexOf(",");

        return comma >= 0
                && inside.substring(
                comma + 1
        ).trim().startsWith("{");
    }
