    /**
     * Stage 2 (qwen2.5:7b):
     * MongoDB query + deterministic SQL -> logical execution steps.
     */
    public static String buildStepsPrompt(
            String mongoQuery,
            String sqlQuery,
            String parsedMongoQuery
    ) {

        String lowerMongo = mongoQuery.toLowerCase();

        List<String> operations = new ArrayList<>();

        boolean hasFind = lowerMongo.contains(".find(");
        boolean hasCount = lowerMongo.contains(".countdocuments(");
        boolean hasWhere = lowerMongo.contains("$match") || hasFindFilter(mongoQuery);
        boolean hasSelect = hasProjection(mongoQuery);
        boolean hasGroup = lowerMongo.contains("$group");
        boolean hasSort = lowerMongo.contains(".sort(") || lowerMongo.contains("$sort");
        boolean hasOffset = lowerMongo.contains(".skip(") || lowerMongo.contains("$skip");
        boolean hasLimit = lowerMongo.contains(".limit(") || lowerMongo.contains("$limit");
        boolean hasJoin = lowerMongo.contains("$lookup");
        boolean hasUnwind = lowerMongo.contains("$unwind");

        if (hasFind) operations.add("FIND");
        if (hasCount) operations.add("COUNT");
        if (hasWhere) operations.add("WHERE");
        if (hasSelect) operations.add("SELECT");
        if (hasGroup) { operations.add("GROUP BY"); operations.add("AGGREGATE"); }
        if (hasSort) operations.add("ORDER BY");
        if (hasOffset) operations.add("OFFSET");
        if (hasLimit) operations.add("LIMIT");
        if (hasJoin) operations.add("JOIN");
        if (hasUnwind) operations.add("UNWIND");

        StringBuilder checklist = new StringBuilder();
        for (String op : operations) {
            checklist.append("- ").append(op).append("\n");
        }

        int checklistCount = operations.size();

        // -----------------------------------------------------
        // Dynamically build "do not merge" warnings only for
        // operation pairs that actually co-occur in this query,
        // instead of one fixed example irrelevant to other shapes.
        // -----------------------------------------------------

        StringBuilder mergeWarnings = new StringBuilder();

        if (hasFind && hasWhere) {
            mergeWarnings.append(
                    "- FIND and WHERE are ALWAYS two separate steps, "
                            + "even though they appear in the same find({...}) "
                            + "call and even though the resulting SQL puts "
                            + "SELECT/FROM and WHERE in one statement. Never "
                            + "describe both the retrieval and the filter "
                            + "condition inside a single step's description.\n"
            );
        }

        if (hasGroup) {
            mergeWarnings.append(
                    "- GROUP BY and AGGREGATE are ALWAYS two separate "
                            + "steps, even though a single $group stage "
                            + "produces both the grouping and the aggregate "
                            + "function together.\n"
            );
        }

        if (hasJoin && hasWhere) {
            mergeWarnings.append(
                    "- JOIN and WHERE are ALWAYS two separate steps, "
                            + "even when $lookup and $match both appear in "
                            + "the same aggregation pipeline.\n"
            );
        }

        if (hasSort && hasLimit) {
            mergeWarnings.append(
                    "- ORDER BY and LIMIT are ALWAYS two separate steps, "
                            + "even when sort() and limit() are chained "
                            + "together in the same query.\n"
            );
        }

        if (hasOffset && hasLimit) {
            mergeWarnings.append(
                    "- OFFSET and LIMIT are ALWAYS two separate steps, "
                            + "even when skip() and limit() are chained "
                            + "together in the same query.\n"
            );
        }

        if (mergeWarnings.isEmpty()) {
            mergeWarnings.append(
                    "- Every operation in the checklist above gets its "
                            + "own step. Never combine two operations, even "
                            + "if they appear close together in the query or "
                            + "in the same SQL statement.\n"
            );
        }

        // -----------------------------------------------------
        // Dynamically build a worked example skeleton showing
        // exactly checklistCount steps, using this query's own
        // operations — not a fixed unrelated example.
        // -----------------------------------------------------

        StringBuilder exampleSteps = new StringBuilder();
        for (int i = 0; i < operations.size(); i++) {
            String op = operations.get(i);
            exampleSteps.append("    {\n")
                    .append("      \"operation\": \"").append(op).append("\",\n")
                    .append("      \"mongodb\": \"<fragment for ").append(op).append(">\",\n")
                    .append("      \"sql\": \"<fragment for ").append(op).append(">\",\n")
                    .append("      \"description\": \"<explains only ").append(op).append(">\"\n")
                    .append("    }")
                    .append(i < operations.size() - 1 ? ",\n" : "\n");
        }

        return """
            You are an educational assistant for TRIQL,
            a visual MongoDB-to-SQL learning platform.

            Your task is to explain the logical execution
            of the MongoDB query by matching each MongoDB
            operation to its SQL counterpart.

            Original MongoDB query:
            %s

            Parsed MongoDB query:
            %s

            Deterministic SQL:
            %s

            The MongoDB query contains EXACTLY these
            operations:

            %s

            You MUST produce EXACTLY %d step object(s) — one
            step for EACH operation listed above, never fewer,
            never combined into one step.

            CRITICAL — DO NOT MERGE STEPS:
            %s
            REQUIRED SHAPE FOR THIS QUERY (fill in the real
            fragments and descriptions — do not leave the
            placeholder text, and do not add, remove, merge,
            or reorder these %d steps):

            {
              "explanation": "one short paragraph",
              "steps": [
            %s
              ]
            }

            STRICT RULES:

            1. Include every operation in the checklist —
               exactly %d steps total, no more, no fewer.

            2. Do NOT add operations that are not present
               in the checklist.

            3. Do NOT invent MongoDB operations.

            4. Do NOT modify the deterministic SQL.

            5. Each MongoDB operation must correspond to
               the correct SQL fragment.

            6. find() maps to SELECT/FROM.

            7. MongoDB filter conditions map to WHERE.

            8. Projection maps to SELECT columns.

            9. sort() maps to ORDER BY.

            10. skip() maps to OFFSET.

            11. limit() maps to LIMIT.

            12. countDocuments() maps to COUNT(*).

            13. $match maps to WHERE.

            14. $group maps to GROUP BY.

            15. MongoDB aggregation operators such as
                $sum, $avg, $min and $max map to SQL
                aggregate functions.

            16. $lookup maps to JOIN.

            17. $in / $nin map to WHERE ... IN (...) / NOT IN (...).

            18. $or / $and map to WHERE conditions combined with
                OR / AND.

            19. $exists maps to WHERE ... IS NOT NULL / IS NULL.

            20. $regex maps to WHERE ... LIKE.

            21. $unwind maps to a JOIN against a related table —
                this mapping is a best-effort assumption, not a
                verified schema relationship; mention this
                caveat when the step describes $unwind
                specifically.

            22. Do NOT fabricate row counts.

            23. Do NOT generate sample data.

            24. Do NOT execute the query.

            25. Each "mongodb" field must contain only the
                relevant MongoDB fragment.

            26. Each "sql" field must contain only the
                relevant SQL fragment.

            27. Each description must be 1-2 simple sentences,
                describing ONLY its own operation — never
                describe another step's operation inside a
                different step's description.

            28. Keep the execution order logical.

            29. Before finalizing, count your steps and
                compare the count against the checklist above.
                If the counts do not match, add or split steps
                until they do.

            30. Output ONLY raw JSON.
            """.formatted(
                mongoQuery,
                parsedMongoQuery,
                sqlQuery,
                checklist.toString(),
                checklistCount,
                mergeWarnings.toString(),
                checklistCount,
                exampleSteps.toString(),
                checklistCount
        );
    }


